export function getVendor(slug: string) {
  return vendors.find((v) => v.slug === slug);
}

export function getVendorsByCategory(category: VendorCategorySlug) {
  return vendors.filter((v) => v.category === category);
}

export function getVendorsByEventType(eventType: string) {
  return vendors.filter((v) => v.eventTypes.includes(eventType as never));
}

export function getFeaturedVendors(count = 6) {
  return [...vendors].sort((a, b) => b.rating - a.rating).slice(0, count);
}

export function getRelatedVendors(slug: string, count = 3) {
  const current = getVendor(slug);
  if (!current) return [];
  return vendors
    .filter((v) => v.slug !== slug && v.eventTypes.some((e) => current.eventTypes.includes(e)))
    .slice(0, count);
}
